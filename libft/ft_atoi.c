#include "libft.h"

int	ft_atoi(const char *nptr)
{
	int		signe;
	long	resultat;
	int		i;

	signe = 1;
	i = 0;
	while (nptr[i] == ' ' || (nptr[i] >= 9 && nptr[i] <= 13))
		i++;
	if (nptr[i] == '+' || nptr[i] == '-')
	{
		if (nptr[i] == '-')
			signe *= -1;
		i++;
	}
	resultat = 0;
	while (nptr[i] >= '0' && nptr[i] <= '9')
	{
		resultat = resultat * 10 + (nptr[i] - '0');
		i++;
	}
	return ((int)(signe * resultat));
}

#include "libft.h"

char	*ft_strdup(const char *s)
{
	char	*copy;
	size_t	size;
	size_t	i;

	size = ft_strlen(s);
	copy = malloc(sizeof(char) * size + 1);
	if (copy == NULL)
		return (NULL);
	i = 0;
	while (s[i])
	{
		copy[i] = s[i];
		i++;
	}
	copy[i] = '\0';
	return (copy);
}
